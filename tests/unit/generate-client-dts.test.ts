import { createSourceFile as tsCreateSourceFile, ScriptTarget } from 'typescript'
import { describe, expect, it } from 'vitest'

import { generateClientDts } from '../../packages/theo/src/vite-plugin/app-typed-client.js'
import type { TheoManifest } from '../../packages/theo/src/server/scan/manifest.js'

const tsLatest = ScriptTarget.Latest

function mkManifest(routes: TheoManifest['routes']): TheoManifest {
  return {
    version: 1,
    generatedAt: '2026-06-01T00:00:00.000Z',
    routes,
    actions: [],
    websockets: [],
  }
}

const DTS_OUT = '/proj/.theokit/client.d.ts'
const SERVER_DIR = '/proj/server'

describe('generateClientDts', () => {
  it('emits the AUTO-GENERATED header + eslint-disable + declared module', () => {
    const out = generateClientDts({
      manifest: mkManifest([]),
      dtsOutPath: DTS_OUT,
      serverDir: SERVER_DIR,
    })
    expect(out).toContain('AUTO-GENERATED by theokit')
    expect(out).toContain('/* eslint-disable */')
    expect(out).toContain("declare module '@theo/client'")
    expect(out).toContain('export const client: AppClient')
  })

  it('generates an empty stub when no routes are present', () => {
    const out = generateClientDts({
      manifest: mkManifest([]),
      dtsOutPath: DTS_OUT,
      serverDir: SERVER_DIR,
    })
    expect(out).toContain('No routes detected')
  })

  it('renders a single GET route as `users.get`', () => {
    const out = generateClientDts({
      manifest: mkManifest([
        { filePath: 'routes/users.ts', routePath: '/api/users', paramNames: [], methods: ['GET'] },
      ]),
      dtsOutPath: DTS_OUT,
      serverDir: SERVER_DIR,
    })
    expect(out).toContain('users:')
    expect(out).toMatch(/get:.+typeof _r0_GET/)
    expect(out).toContain("import type { GET as _r0_GET } from '../server/routes/users'")
  })

  it('renders GET + POST on the same route as `users.get` + `users.post`', () => {
    const out = generateClientDts({
      manifest: mkManifest([
        {
          filePath: 'routes/users.ts',
          routePath: '/api/users',
          paramNames: [],
          methods: ['GET', 'POST'],
        },
      ]),
      dtsOutPath: DTS_OUT,
      serverDir: SERVER_DIR,
    })
    expect(out).toMatch(/get:.+typeof _r0_GET/)
    expect(out).toMatch(/post:.+typeof _r0_POST/)
  })

  it('renders dynamic params with proper `params: { id: string }` type', () => {
    const out = generateClientDts({
      manifest: mkManifest([
        {
          filePath: 'routes/users.[id].ts',
          routePath: '/api/users/:id',
          paramNames: ['id'],
          methods: ['GET', 'DELETE'],
        },
      ]),
      dtsOutPath: DTS_OUT,
      serverDir: SERVER_DIR,
    })
    expect(out).toContain('params: { id: string }')
  })

  // Regression — theokit 0.2.2 fix: the previous codegen emitted
  // `(opts: params: { id: string } & TheoFetchOptions<...>)` which is invalid
  // TypeScript syntax (parser reads `params:` as a parameter label, then `{...}`
  // as the type — combination invalid). Result: dogfood-app typecheck failed
  // with TS1005/TS1359/TS1138 when consuming the published theokit@0.2.1.
  // Fix wraps the intersection in `{ params: {...} }` so the signature is
  // `(opts: { params: { id: string } } & TheoFetchOptions<...>)`.
  it('regression: dynamic-param signature uses `(opts: { params: ... } & ...)` wrap (not `opts: params:` flat)', () => {
    const out = generateClientDts({
      manifest: mkManifest([
        {
          filePath: 'routes/users.[id].ts',
          routePath: '/api/users/:id',
          paramNames: ['id'],
          methods: ['GET', 'DELETE'],
        },
      ]),
      dtsOutPath: DTS_OUT,
      serverDir: SERVER_DIR,
    })
    // Must contain the wrapped form
    expect(out).toContain('(opts: { params: { id: string } } & import')
    // Must NOT contain the broken flat form
    expect(out).not.toContain('(opts: params: {')
    // Parse with ts.createSourceFile to catch any syntax error globally —
    // this catches future regressions in other intersection points.
    // parseDiagnostics is attached to the SourceFile when set==true.
    const sf = tsCreateSourceFile('out.d.ts', out, tsLatest, true)
    const diags = (sf as unknown as { parseDiagnostics?: ReadonlyArray<{ messageText: string }> })
      .parseDiagnostics
    if (diags && diags.length > 0) {
      throw new Error(
        `Generated client.d.ts has ${diags.length} parse error(s): ${diags.map((d) => d.messageText).join(' | ')}`,
      )
    }
  })

  // Regression — theokit 0.2.2 fix: multi-param routes (`.:user/:id` etc) must
  // also wrap correctly. Catch double-param edge case.
  it('regression: multi-param route also uses `{ params: {...} }` wrap', () => {
    const out = generateClientDts({
      manifest: mkManifest([
        {
          filePath: 'routes/users.[user]/posts.[id].ts',
          routePath: '/api/users/:user/posts/:id',
          paramNames: ['user', 'id'],
          methods: ['GET'],
        },
      ]),
      dtsOutPath: DTS_OUT,
      serverDir: SERVER_DIR,
    })
    expect(out).toContain('(opts: { params: { user: string; id: string } } & import')
    expect(out).not.toMatch(/\(opts: params:/)
  })

  it('uses relative import paths from the .d.ts location (no aliases assumed)', () => {
    const out = generateClientDts({
      manifest: mkManifest([
        { filePath: 'routes/posts.ts', routePath: '/api/posts', paramNames: [], methods: ['GET'] },
      ]),
      dtsOutPath: DTS_OUT,
      serverDir: SERVER_DIR,
    })
    expect(out).toContain("from '../server/routes/posts'")
  })

  it('EC-2: normalizes kebab-case segments to camelCase', () => {
    const out = generateClientDts({
      manifest: mkManifest([
        {
          filePath: 'routes/user-profiles.ts',
          routePath: '/api/user-profiles',
          paramNames: [],
          methods: ['GET'],
        },
      ]),
      dtsOutPath: DTS_OUT,
      serverDir: SERVER_DIR,
    })
    expect(out).toContain('userProfiles:')
    expect(out).not.toContain('user-profiles:')
  })

  it('EC-2: unsafe segments (digit-leading) emit as bracket-access key', () => {
    const out = generateClientDts({
      manifest: mkManifest([
        { filePath: 'routes/2fa.ts', routePath: '/api/2fa', paramNames: [], methods: ['POST'] },
      ]),
      dtsOutPath: DTS_OUT,
      serverDir: SERVER_DIR,
    })
    expect(out).toMatch(/'2fa':/)
  })

  it('EC-3: collision method vs sub-namespace renames sub-namespace with `_` suffix', () => {
    const out = generateClientDts({
      manifest: mkManifest([
        // GET /api/posts — declares method `get`
        { filePath: 'routes/posts.ts', routePath: '/api/posts', paramNames: [], methods: ['GET'] },
        // POST /api/posts/get — collides with method name `get` from above
        {
          filePath: 'routes/posts/get.ts',
          routePath: '/api/posts/get',
          paramNames: [],
          methods: ['POST'],
        },
      ]),
      dtsOutPath: DTS_OUT,
      serverDir: SERVER_DIR,
    })
    expect(out).toContain('// WARNING (EC-3)')
    expect(out).toContain('get_:')
    expect(out).toMatch(/posts:[\s\S]*get:/)
  })

  it('EC-8: Windows path separators are normalized in import paths', () => {
    const out = generateClientDts({
      manifest: mkManifest([
        {
          filePath: 'routes\\posts.ts',
          routePath: '/api/posts',
          paramNames: [],
          methods: ['GET'],
        },
      ]),
      dtsOutPath: DTS_OUT,
      serverDir: SERVER_DIR,
    })
    expect(out).not.toContain('\\\\')
    expect(out).toMatch(/from '\.\.\/server\/routes\/posts'/)
  })

  it('skips routes whose methods array is empty', () => {
    const out = generateClientDts({
      manifest: mkManifest([
        { filePath: 'routes/util.ts', routePath: '/api/util', paramNames: [], methods: [] },
        { filePath: 'routes/x.ts', routePath: '/api/x', paramNames: [], methods: ['GET'] },
      ]),
      dtsOutPath: DTS_OUT,
      serverDir: SERVER_DIR,
    })
    expect(out).toContain('x:')
    expect(out).not.toMatch(/util:.+get/)
  })

  it('routes without methods declared (legacy manifest) are skipped silently', () => {
    const out = generateClientDts({
      manifest: mkManifest([{ filePath: 'routes/x.ts', routePath: '/api/x', paramNames: [] }]),
      dtsOutPath: DTS_OUT,
      serverDir: SERVER_DIR,
    })
    expect(out).toContain('No routes detected')
  })

  it('nested route paths produce nested namespaces (posts.id.comments.get)', () => {
    const out = generateClientDts({
      manifest: mkManifest([
        {
          filePath: 'routes/posts.[id].comments.ts',
          routePath: '/api/posts/:id/comments',
          paramNames: ['id'],
          methods: ['GET', 'POST'],
        },
      ]),
      dtsOutPath: DTS_OUT,
      serverDir: SERVER_DIR,
    })
    expect(out).toMatch(/posts:[\s\S]*id:[\s\S]*comments:/)
  })
})
