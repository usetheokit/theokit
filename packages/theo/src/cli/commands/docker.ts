import { existsSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

import { loadConfig } from '../../config/load-config.js'
import { AUTHORED_AGENT_CONTEXT } from '../cleanup/cleanup.js'

function detectPkgManager(cwd: string): PkgManager {
  if (existsSync(resolve(cwd, 'pnpm-lock.yaml'))) return 'pnpm'
  if (existsSync(resolve(cwd, 'yarn.lock'))) return 'yarn'
  return 'npm'
}

type PkgManager = 'pnpm' | 'npm' | 'yarn'

interface DockerfileInput {
  readonly pkgManager: PkgManager
  /** Top-level directories holding the server and agent sources, e.g. `['src']` for the scaffold. */
  readonly sourceRoots: readonly string[]
  /** The configured build output directory, `.theokit` by default. */
  readonly distDir: string
  readonly hasConfigFile: boolean
  readonly hasPnpmWorkspace: boolean
}

/**
 * The installed CLI, by path. `npx theo build` asked the registry for a package named `theo`, an
 * unrelated design-tokens tool, then installed and ran it inside the image build (#1069). A path
 * into `node_modules/.bin` cannot fall back to the registry under any package manager.
 */
const THEOKIT_BIN = './node_modules/.bin/theokit'

/**
 * The top-level directory a configured path lives in. The runner copies whole roots: the scaffold's
 * `src/server` imports `src/shared`, so copying only `serverDir` would leave an import dangling.
 */
function topLevelDir(path: string): string {
  return path.replace(/^\.\//, '').split('/')[0]
}

function generateDockerfile(input: DockerfileInput): string {
  const { pkgManager, distDir } = input
  const installCmd = {
    pnpm: 'RUN corepack enable && pnpm install --frozen-lockfile',
    npm: 'RUN npm ci',
    yarn: 'RUN yarn install --frozen-lockfile',
  }[pkgManager]

  const lockfile = {
    pnpm: 'pnpm-lock.yaml',
    npm: 'package-lock.json',
    yarn: 'yarn.lock',
  }[pkgManager]

  // pnpm 10 reads `allowBuilds` from pnpm-workspace.yaml; installing without it leaves esbuild unbuilt.
  const manifests = [
    'package.json',
    lockfile,
    ...(pkgManager === 'pnpm' && input.hasPnpmWorkspace ? ['pnpm-workspace.yaml'] : []),
  ]

  const copySources = [...new Set(input.sourceRoots)].map(
    (root) => `COPY --from=builder /app/${root} ./${root}`,
  )

  return [
    '# Generated by TheoKit',
    '# Multi-stage build for production',
    '',
    '# Stage 1: Build',
    'FROM node:22-alpine AS builder',
    'WORKDIR /app',
    `COPY ${manifests.join(' ')} ./`,
    installCmd,
    'COPY . .',
    `RUN ${THEOKIT_BIN} build`,
    '',
    '# Stage 2: Production',
    'FROM node:22-alpine AS runner',
    'WORKDIR /app',
    'ENV NODE_ENV=production',
    // Inside a container `localhost` answers nobody, the image's own health check included (#402).
    'ENV HOST=0.0.0.0',
    'ENV PORT=3000',
    `COPY --from=builder /app/${distDir} ./${distDir}`,
    ...copySources,
    ...(input.hasConfigFile ? ['COPY --from=builder /app/theo.config.ts ./theo.config.ts'] : []),
    ...manifests.map((file) => `COPY --from=builder /app/${file} ./${file}`),
    'COPY --from=builder /app/node_modules ./node_modules',
    '',
    'EXPOSE 3000',
    `CMD ["${THEOKIT_BIN}", "start"]`,
    '',
  ].join('\n')
}

/**
 * `.theokit` is both the build output and the agent context (#1079). The context a person writes
 * (THEO.md, rules, personalities ...) goes into the image; local agent state such as memory and MCP
 * tokens stays out, and so does a stale local build, which the image rebuilds anyway.
 */
function generateDockerignore(distDir = '.theokit'): string {
  return [
    'node_modules',
    '.git',
    `${distDir}/*`,
    // A re-included directory brings its contents: Docker matches a pattern against every parent.
    ...AUTHORED_AGENT_CONTEXT.map((entry) => `!${distDir}/${entry}`),
    'dist',
    '.env',
    '.env.*',
    '!.env.example',
    '*.log',
    '.DS_Store',
    '.vscode',
    '.idea',
    'Dockerfile',
    '.dockerignore',
    '',
  ].join('\n')
}

export async function dockerCommand(options?: { force?: boolean }): Promise<void> {
  const cwd = process.cwd()
  const dockerfilePath = resolve(cwd, 'Dockerfile')
  const dockerignorePath = resolve(cwd, '.dockerignore')

  const pkgManager = detectPkgManager(cwd)
  const { serverDir, agentsDir, distDir } = await loadConfig(cwd)
  const dockerfile = generateDockerfile({
    pkgManager,
    sourceRoots: [topLevelDir(serverDir), topLevelDir(agentsDir)],
    distDir,
    hasConfigFile: existsSync(resolve(cwd, 'theo.config.ts')),
    hasPnpmWorkspace: existsSync(resolve(cwd, 'pnpm-workspace.yaml')),
  })

  // `wx` refuses an existing file in the same call that creates it. A separate exists check
  // followed by a write leaves a window, wider now that the config load sits between them.
  try {
    writeFileSync(dockerfilePath, dockerfile, { flag: options?.force ? 'w' : 'wx' })
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code !== 'EEXIST') throw err
    console.log('\n  ⚠ Dockerfile already exists. Use --force to overwrite.\n')
    return
  }
  writeFileSync(dockerignorePath, generateDockerignore(distDir))

  console.log(`\n  ✓ Generated Dockerfile (${pkgManager})`)
  console.log(`  ✓ Generated .dockerignore`)
  console.log(`\n  Next steps:`)
  console.log(`    docker build -t my-app .`)
  console.log(`    docker run -p 3000:3000 my-app\n`)
}
