// M62 — `@theokit/agents/tools`: pass-through of `@theokit/sdk-tools`'s ready-made tool factories
// (`createReadFileTool`, `createShellTool`, … + `withName`/`withDescription`). These are stateless
// third-party factories — enriching them would be reinventing the SDK-tools' own sugar (blueprint Q5),
// so this is a pure re-export (parsimony Rung 9). The consumer imports its built-in tools from the
// Theokit layer, not from `@theokit/sdk-tools` directly. `@theokit/sdk-tools` is a hard DEPENDENCY of
// this package, not an optional peer: this file re-exports it statically, so a missing copy would
// break the subpath at import time rather than degrade. (The manifest said "optional peer" in
// `peerDependenciesMeta` long after the move — orphan metadata the npm client never reads. Removed,
// and guarded, in backlog B-M67-01 item 6.)

// M90 — the list is NAMED, not `export *`.
//
// The decision not to wrap (rung 9, above) still holds: enumerating is not wrapping. What changes is
// something else — with `export *`, a symbol removed upstream simply stops existing on the surface
// and THIS layer's build passes; the consumer finds out at a call site. With explicit names, `tsc`
// points at the line. It is the property `auth-entry.ts` already had and these five did not.
//
// The surface is preserved WHOLE (measured: 93 symbols, parity identical to the source). Reducing it
// would be breaking for other consumers, and M73 already wrote the rule in `auth-entry.ts`:
// enriching never reduces. If a symbol is ever deliberately withheld, the reason comes written here.
//
