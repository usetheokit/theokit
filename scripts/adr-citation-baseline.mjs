#!/usr/bin/env node
/**
 * Write the ADR-citation baseline `check-doc-citations.mjs` reads.
 *
 * ## Why a generator and not a hand-kept list
 *
 * The list is 190 lines today. Hand-editing it is how a record becomes an excuse list: a line added
 * to make a run green is indistinguishable from one that was always there. Generating it makes
 * regeneration a visible, reviewable act — the diff shows exactly which citations were adopted.
 *
 * ## Why running it is a decision, never a side effect
 *
 * `--write` is required. A run with no flag prints what WOULD be written and changes nothing, so
 * the file cannot be refreshed by accident in the middle of another task. The same reason
 * `run_code_quality.py --write-baseline` is explicit.
 *
 * **Never regenerate to make a failing run pass.** The gate fails on a citation that is NOT in the
 * baseline, which means somebody added a reference to a document that does not exist. Adopting it
 * silences the finding and keeps the defect.
 */
import { execFileSync } from 'node:child_process'
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'

const ADR_CITATION = /\bADR[ -](\d{4})\b/g
const ROOT = resolve(dirname(new URL(import.meta.url).pathname), '..')
const OUT = join(ROOT, 'scripts', 'adr-citation-baseline.txt')

/** Every ADR number that exists, across every `docs/adr/` in the tree. */
function existingIds(root) {
  const ids = new Set()
  for (const dir of [join(root, 'docs', 'adr'), join(root, 'apps', 'theocode', 'docs', 'adr')]) {
    if (!existsSync(dir)) continue
    for (const entry of readdirSync(dir)) {
      const head = entry.slice(0, 4)
      if (/^\d{4}$/.test(head)) ids.add(head)
    }
  }
  return ids
}

/** The tracked source set, by definition rather than by a walk that a generated file can creep into. */
function sources(root) {
  // eslint-disable-next-line sonarjs/no-os-command-from-path -- toolchain binary, fixed argv
  return execFileSync('git', ['-C', root, 'ls-files', '-z', '*.ts', '*.tsx', '*.mjs'], {
    encoding: 'utf-8',
  })
    .split('\0')
    .filter((f) => f && !f.includes('/node_modules/'))
}

const HEADER = `# ADR citations that already existed when the gate learned to read source — B-255.
#
# NOT forgiveness. Every line here is still reported on every run and counted separately, so the
# debt stays visible; what the file stops doing is failing a change that did not cause it.
#
# TRIAGED 2026-09-22 before this was first written, because a baseline nobody understood would be a
# list of excuses rather than a record:
#   * \`docs/adr/\` holds 0001..0017 — seventeen documents.
#   * Every one of the 33 absent numbers cited here is 0018 or above.
#   * \`git log --diff-filter=D -- 'docs/adr/*.md'\` returns NOTHING.
# So not one of these is a renumbering or a deletion. They cite documents that were never written.
#
# Format: <path>|<NNNN>. The line number is deliberately absent — it moves, and the pair does not.
# A NEW unresolvable citation is not in this file and fails the gate, which is the whole point.
#
# Generated by \`node scripts/adr-citation-baseline.mjs --write\`. Never regenerate to make a run
# green: that turns the record into the excuse list it was written not to be.
`

/** The unresolvable `path|number` pairs in tracked source, which is what the baseline records. */
function collectPairs(root, have) {
  const pairs = new Set()
  for (const rel of sources(root)) {
    let text
    try {
      text = readFileSync(join(root, rel), 'utf-8')
    } catch {
      continue
    }
    for (const line of text.split('\n')) {
      if (line.includes('adr-citation-ok:')) continue
      for (const m of line.matchAll(ADR_CITATION)) {
        if (!have.has(m[1])) pairs.add(`${rel}|${m[1]}`)
      }
    }
  }
  return pairs
}

function main() {
  const pairs = collectPairs(ROOT, existingIds(ROOT))
  const body = HEADER + [...pairs].sort().join('\n') + '\n'
  if (!process.argv.includes('--write')) {
    console.error(`${pairs.size} pair(s) would be written to scripts/adr-citation-baseline.txt`)
    console.error('Nothing changed. Pass --write to adopt them, and read the header first.')
    return
  }
  writeFileSync(OUT, body, 'utf-8')
  console.error(`wrote ${pairs.size} pair(s) to scripts/adr-citation-baseline.txt`)
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(new URL(import.meta.url).pathname)) {
  main()
}
